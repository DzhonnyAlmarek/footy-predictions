-- Optional prerequisite for the delegated-prediction feature.
-- Run against an isolated Neon branch first; do not modify the working branch
-- before reviewing the migration and validating its rollback.
-- Existing forecasts, scores and points are untouched.
-- Legacy migrations inserted some stage and prediction IDs explicitly,
-- leaving their identity sequences behind existing IDs. Synchronize only
-- sequence counters; do not rewrite any existing row.
SELECT setval('footy_cutover.stages_id_seq',
  GREATEST(
    (SELECT COALESCE(MAX(id), 1) FROM footy_cutover.stages),
    (SELECT last_value FROM footy_cutover.stages_id_seq)), true);
SELECT setval('footy_cutover.predictions_id_seq',
  GREATEST(
    (SELECT COALESCE(MAX(id), 1) FROM footy_cutover.predictions),
    (SELECT last_value FROM footy_cutover.predictions_id_seq)), true);

CREATE TABLE IF NOT EXISTS cutover_auth.admin_prediction_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prediction_id bigint NOT NULL,
  match_id bigint NOT NULL,
  participant_id uuid NOT NULL,
  actor_id uuid NOT NULL,
  previous_home_pred integer,
  previous_away_pred integer,
  home_pred integer NOT NULL CHECK (home_pred BETWEEN 0 AND 99),
  away_pred integer NOT NULL CHECK (away_pred BETWEEN 0 AND 99),
  source_note text NOT NULL CHECK (length(source_note) BETWEEN 3 AND 160),
  recorded_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_prediction_audit_match_idx
  ON cutover_auth.admin_prediction_audit(match_id, participant_id, recorded_at DESC);
