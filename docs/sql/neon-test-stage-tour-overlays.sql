-- DESIGN ONLY. Apply only to isolated Neon branch supabase-full-migration-work-2026-10-09.
-- Do not run against default Neon branch, production Supabase, or migration_source.
-- This schema stores stage/tour metadata overlays. New match references require a later,
-- separately reviewed migration; existing match foreign keys remain unchanged.
BEGIN;
CREATE TABLE IF NOT EXISTS footy_sandbox.stage_drafts (
  draft_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 160),
  matches_required integer NOT NULL DEFAULT 56 CHECK (matches_required BETWEEN 1 AND 1000),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','locked')),
  is_current boolean NOT NULL DEFAULT false,
  is_deleted boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS footy_sandbox.stage_edits (
  stage_id bigint PRIMARY KEY REFERENCES migration_source.stages(id),
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 160),
  matches_required integer NOT NULL CHECK (matches_required BETWEEN 1 AND 1000),
  -- Status and current-stage changes are intentionally excluded until publishing rules are ported.
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS footy_sandbox.tour_drafts (
  draft_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  imported_stage_id bigint REFERENCES migration_source.stages(id),
  draft_stage_id bigint REFERENCES footy_sandbox.stage_drafts(draft_id),
  tour_no text NOT NULL CHECK (length(btrim(tour_no)) BETWEEN 1 AND 40),
  name text,
  is_deleted boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tour_drafts_one_stage CHECK ((imported_stage_id IS NOT NULL) <> (draft_stage_id IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS tour_drafts_imported_unique ON footy_sandbox.tour_drafts(imported_stage_id,tour_no) WHERE NOT is_deleted AND imported_stage_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS tour_drafts_new_unique ON footy_sandbox.tour_drafts(draft_stage_id,tour_no) WHERE NOT is_deleted AND draft_stage_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS footy_sandbox.tour_edits (
  tour_id bigint PRIMARY KEY REFERENCES migration_source.tours(id),
  name text,
  -- Tour number/stage movement is intentionally excluded to protect existing match links.
  updated_at timestamptz NOT NULL DEFAULT now()
);
COMMIT;
